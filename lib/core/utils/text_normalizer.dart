/// Utility to normalize Vietnamese text for diacritic-insensitive search
class TextNormalizer {
  TextNormalizer._();


  static final Map<String, String> _charMap = {
    'á': 'a', 'à': 'a', 'ả': 'a', 'ã': 'a', 'ạ': 'a',
    'ă': 'a', 'ắ': 'a', 'ằ': 'a', 'ẳ': 'a', 'ẵ': 'a', 'ặ': 'a',
    'â': 'a', 'ấ': 'a', 'ầ': 'a', 'ẩ': 'a', 'ẫ': 'a', 'ậ': 'a',
    'é': 'e', 'è': 'e', 'ẻ': 'e', 'ẽ': 'e', 'ẹ': 'e',
    'ê': 'e', 'ế': 'e', 'ề': 'e', 'ể': 'e', 'ễ': 'e', 'ệ': 'e',
    'ó': 'o', 'ò': 'o', 'ỏ': 'o', 'õ': 'o', 'ọ': 'o',
    'ô': 'o', 'ố': 'o', 'ồ': 'o', 'ổ': 'o', 'ỗ': 'o', 'ộ': 'o',
    'ơ': 'o', 'ớ': 'o', 'ờ': 'o', 'ở': 'o', 'ỡ': 'o', 'ợ': 'o',
    'ú': 'u', 'ù': 'u', 'ủ': 'u', 'ũ': 'u', 'ụ': 'u',
    'ư': 'u', 'ứ': 'u', 'ừ': 'u', 'ử': 'u', 'ữ': 'u', 'ự': 'u',
    'í': 'i', 'ì': 'i', 'ỉ': 'i', 'ĩ': 'i', 'ị': 'i',
    'ý': 'y', 'ỳ': 'y', 'ỷ': 'y', 'ỹ': 'y', 'ỵ': 'y',
    'đ': 'd',
  };

  /// Strips Vietnamese diacritics and converts to lowercase: e.g. "Cà phê" -> "ca phe"
  static String normalize(String input) {
    String result = input.toLowerCase();
    _charMap.forEach((key, value) {
      result = result.replaceAll(key, value);
    });
    return result.trim();
  }

  /// Checks if target string matches query ignoring case and Vietnamese diacritics
  static bool matches(String target, String query) {
    if (query.trim().isEmpty) return true;
    final normalizedTarget = normalize(target);
    final normalizedQuery = normalize(query);
    return normalizedTarget.contains(normalizedQuery);
  }
}
